#!/usr/bin/env bash
# Register the Rust message crates of an installed ROS 2 distribution with
# colcon-ros-cargo, without touching /opt/ros.
#
# colcon-ros-cargo discovers Rust message crates through the "rust_packages"
# ament index (share/ament_index/resource_index/rust_packages/<pkg>) and writes
# the matching [patch.crates-io] entries into <workspace>/.cargo/config.toml,
# pointing each crate at <prefix>/share/<pkg>/rust. The Debian ros-<distro>-*
# packages ship the crates under share/<pkg>/rust but do not ship that index,
# so colcon finds nothing and the crate's Cargo.toml had to carry
# distro-specific paths plus a sed to retarget them.
#
# This script builds a user-local ament prefix that exposes the missing index
# (marker files) together with share/<pkg> -> /opt/ros/<distro>/share/<pkg>
# symlinks, so colcon resolves every crate to its real location automatically.
# Re-run it after installing a new distribution (or after rosidl_generator_rs
# packages are added/removed); it is idempotent.

set -euo pipefail

ROS_DISTRO="${ROS_DISTRO:-}"
if [[ -z "$ROS_DISTRO" ]]; then
  echo "error: ROS_DISTRO is empty; source /opt/ros/<distro>/setup.bash first" >&2
  exit 1
fi

SRC="/opt/ros/${ROS_DISTRO}/share"
if [[ ! -d "$SRC" ]]; then
  echo "error: $SRC does not exist" >&2
  exit 1
fi

DST="${ROS2_RUST_INDEX:-$HOME/.local/share/ros2-rust-index}"
INDEX="$DST/share/ament_index/resource_index/rust_packages"

mkdir -p "$INDEX" "$DST/share"
rm -f "$INDEX"/*

count=0
for crate in "$SRC"/*/rust; do
  [[ -d "$crate" ]] || continue
  pkg="$(basename "$(dirname "$crate")")"
  : > "$INDEX/$pkg"                 # marker: the package name is the filename
  ln -sfn "$SRC/$pkg" "$DST/share/$pkg"   # share/<pkg> -> real share/<pkg>
  count=$((count + 1))
done

# colcon's ament prefix-path extension only accepts a prefix that contains a
# 'local_setup.*' file; otherwise it prints
#   "The path '...' in the environment variable AMENT_PREFIX_PATH doesn't
#    contain any 'local_setup.*' files."
# and skips the prefix. This *is* a real ament prefix (it carries an index), it
# just has nothing to set up, so a no-op marker keeps the build output quiet.
for name in local_setup.sh local_setup.bash local_setup.zsh; do
  {
    echo '#!/bin/sh'
    echo '# Generated by register-ros-rust-index.sh.'
    echo '# This ament prefix only carries the rust_packages index; its share/<pkg>'
    echo '# entries are symlinks into /opt/ros/<distro>, so there is nothing to set up.'
  } > "$DST/$name"
  chmod +x "$DST/$name"
done

export_line="export AMENT_PREFIX_PATH=\"$DST:\$AMENT_PREFIX_PATH\""
if ! grep -qxF "$export_line" ~/.bashrc 2>/dev/null; then
  echo "$export_line" >> ~/.bashrc
fi

echo "Registered $count Rust packages from $SRC into $DST"
